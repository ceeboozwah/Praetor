#!/usr/bin/env python3
"""gen_numtests.py — generate the numerical correctness corpus.

Emits `native-tests/num_*.lang` fixtures whose expected values are
computed ONLY with Python's arbitrary-precision integers — Praetor's
own compiler, runtime, and stdlib are never part of the oracle.

Praetor semantics modeled (LANGUAGE.md + backend_llvm/emit.rs):

  * runtime `+ - *` and unary `-` wrap two's-complement at the type's
    width (emitted without nsw/nuw)
  * `<<` wraps at width; `>>` is arithmetic on signed, logical on
    unsigned; a constant shift amount outside `0..width` is a
    compile error (N25A), never generated here as a valid case
  * `/` `%` are `sdiv`/`srem` on signed (TRUNCATE toward zero —
    Python `//` floors, so signed cases use an exact trunc helper)
    and `udiv`/`urem` on unsigned
  * casts `dst(src)`: widening `sext` from a signed source / `zext`
    from unsigned; narrowing `trunc`; same-width bit-preserving
  * `~` is the bitwise complement at the operand's width
  * unadopted literals must fit `i32` (#44); pure-literal trees fold
    at their final type and must fit it — generated `let` decls and
    inline `T(...)` expected values keep every literal adopted
  * NOT generated as valid cases: division/modulo by zero and
    signed `MIN / -1` — both are UB at the LLVM layer

Determinism: `random.Random(SEED)` — Python's Mersenne Twister is
specified reproducible across versions/platforms. Rerun:

    python3 scripts/gen_numtests.py

Exit-code scheme: every fixture returns 42 on success or the 1-based
index of the first failing check, so a corpus FAIL names the exact
assertion. `@stdout` fixtures carry generated `<name>.stdout`
byte-oracles next to them.
"""
import random
from pathlib import Path

SEED = 20260122
OUT = Path(__file__).resolve().parent.parent / "native-tests"

TYPES = {
    "i8": (8, True), "i16": (16, True), "i32": (32, True),
    "i64": (64, True), "u8": (8, False), "u16": (16, False),
    "u32": (32, False), "u64": (64, False),
}
SIGNED = ["i8", "i16", "i32", "i64"]
UNSIGNED = ["u8", "u16", "u32", "u64"]


def bits(ty):
    return TYPES[ty][0]


def signed(ty):
    return TYPES[ty][1]


def lo(ty):
    return -(1 << (bits(ty) - 1)) if signed(ty) else 0


def hi(ty):
    return (1 << (bits(ty) - 1)) - 1 if signed(ty) else (1 << bits(ty)) - 1


def wrap(v, ty):
    """Two's-complement wrap of v into ty's range."""
    m = 1 << bits(ty)
    v &= m - 1
    if signed(ty) and v >= (1 << (bits(ty) - 1)):
        v -= m
    return v


def tdiv(a, b):
    """Truncating signed division — LLVM sdiv semantics."""
    q = abs(a) // abs(b)
    return -q if (a < 0) != (b < 0) else q


def tmod(a, b):
    """Signed remainder — sign follows the dividend (LLVM srem)."""
    return a - tdiv(a, b) * b


def boundaries(ty):
    """Hand-picked edges plus seeded-random samples."""
    vals = [0, 1, lo(ty), hi(ty), lo(ty) + 1, hi(ty) - 1]
    if signed(ty):
        vals += [-1, -2]
    else:
        vals += [hi(ty) // 2, hi(ty) // 2 + 1]
    r = RNG()
    for _ in range(4):
        vals.append(r.randint(lo(ty), hi(ty)))
    return vals


_RNG = None


def RNG():
    global _RNG
    if _RNG is None:
        _RNG = random.Random(SEED)
    return _RNG


def lit(v, ty):
    """`T(v)` — adopted-literal spelling of v as type ty."""
    return f"{ty}({v})"


class Fixture:
    """Accumulates checks; `fail k` names the k-th check."""

    def __init__(self, name, desc):
        self.name = name
        self.head = [
            "// @exit 42",
            "// GENERATED by scripts/gen_numtests.py — do not edit.",
            "// Regenerate: python3 scripts/gen_numtests.py",
            f"// {desc}",
        ]
        self.body = []
        self.k = 0
        self.d = 0

    def decl(self, ty, val):
        n = f"v{self.d}"
        self.d += 1
        self.body.append(f"    let {n}: {ty} = {val};")
        return n

    def chk(self, expr, expect, ty):
        """`expr` (already type ty) must equal wrapped `expect`.
        `!=` outranks `& | ^` in Praetor (C precedence) — parenthesize."""
        self.k += 1
        self.body.append(
            f"    if ({expr}) != {lit(wrap(expect, ty), ty)} "
            f"{{ return {self.k}; }}")

    def chkbool(self, expr, expect):
        """`expr` is a bool; `!=` isn't defined on bools — assert via
        the condition's truth directly."""
        self.k += 1
        cond = f"!({expr})" if expect else expr
        self.body.append(f"    if {cond} {{ return {self.k}; }}")

    def write(self):
        self.body.append("    return 42;")
        src = "\n".join(self.head) + "\n\nfn main() -> i32 {\n" + \
            "\n".join(self.body) + "\n}\n"
        (OUT / f"{self.name}.lang").write_text(src)
        return self.k


def gen_arith(types, name, desc):
    """+,-,* and unary negation — exact when in-range, wrapped when
    the true result escapes the type (both are legal runtime forms;
    only pure-literal folds may overflow-check)."""
    f = Fixture(name, desc + " — valid results exact, overflow wraps two's-complement.")
    for ty in types:
        vs = boundaries(ty)
        for a, b in RNG().sample([(x, y) for x in vs for y in vs], 24):
            va, vb = f.decl(ty, a), f.decl(ty, b)
            for op, sym in (("+", lambda x, y: x + y),
                            ("-", lambda x, y: x - y),
                            ("*", lambda x, y: x * y)):
                f.chk(f"{va} {op} {vb}", sym(a, b), ty)
        val = RNG().choice(vs[2:])
        v = f.decl(ty, val)
        f.chk(f"0 - {v}", -val, ty)  # unary minus / unsigned underflow
    return f


def gen_bitwise():
    f = Fixture("num_020_bitwise",
                "& | ^ ~ — complement is at operand width; "
                "negation wraps.")
    for ty in TYPES:
        vs = boundaries(ty)
        for a, b in RNG().sample([(x, y) for x in vs for y in vs], 12):
            va, vb = f.decl(ty, a), f.decl(ty, b)
            f.chk(f"{va} & {vb}", a & b, ty)
            f.chk(f"{va} | {vb}", a | b, ty)
            f.chk(f"{va} ^ {vb}", a ^ b, ty)
        val = RNG().choice(vs)
        v = f.decl(ty, val)
        f.chk(f"~{v}", ~val, ty)
    return f


def gen_shifts():
    f = Fixture("num_030_shifts",
                "<< >> at amounts 0,1,mid,width-2,width-1 — shl wraps, "
                "shr is arithmetic signed / logical unsigned.")
    for ty in TYPES:
        w = bits(ty)
        for a in boundaries(ty):
            va = f.decl(ty, a)
            for s in (0, 1, w // 2 - 1, w - 2, w - 1):
                if s < 0:
                    continue
                f.chk(f"{va} << {s}", a << s, ty)
                f.chk(f"{va} >> {s}", a >> s, ty)
    return f


def gen_cmp():
    f = Fixture("num_040_cmp",
                "< > <= >= == != on boundary pairs — signed uses "
                "slt/sgt, unsigned ult/ugt on the same bit patterns.")
    for ty in TYPES:
        vs = boundaries(ty)
        for a, b in RNG().sample([(x, y) for x in vs for y in vs], 20):
            va, vb = f.decl(ty, a), f.decl(ty, b)
            for sym, fn in (("<", lambda x, y: x < y),
                            (">", lambda x, y: x > y),
                            ("<=", lambda x, y: x <= y),
                            (">=", lambda x, y: x >= y),
                            ("==", lambda x, y: x == y),
                            ("!=", lambda x, y: x != y)):
                f.chkbool(f"{va} {sym} {vb}", fn(a, b))
    return f


def gen_casts():
    f = Fixture("num_050_casts",
                "8x8 cast matrix on boundary values — sext signed src, "
                "zext unsigned src, trunc narrowing, same-width "
                "bit-preserve.")
    for s in TYPES:
        for a in boundaries(s):
            va = f.decl(s, a)
            for d in TYPES:
                if bits(s) > bits(d):
                    exp = wrap(a, d)                    # trunc
                elif bits(s) == bits(d):
                    exp = wrap(a, d)                    # bit-preserve
                elif signed(s):
                    exp = a                             # sext
                else:
                    exp = a                             # zext
                f.chk(f"{d}({va})", exp, d)
    return f


def gen_divmod():
    f = Fixture("num_060_divmod",
                "sdiv/srem truncate toward zero; udiv/urem floor. "
                "div-by-0 and signed MIN/-1 are UB — excluded by "
                "construction.")
    for ty in TYPES:
        vs = [v for v in boundaries(ty) if v != 0]
        pairs = []
        for a in vs:
            for b in vs:
                if signed(ty) and a == lo(ty) and b == -1:
                    continue                      # sdiv/srem UB
                pairs.append((a, b))
        for a, b in RNG().sample(pairs, min(24, len(pairs))):
            va, vb = f.decl(ty, a), f.decl(ty, b)
            if signed(ty):
                f.chk(f"{va} / {vb}", tdiv(a, b), ty)
                f.chk(f"{va} % {vb}", tmod(a, b), ty)
            else:
                f.chk(f"{va} / {vb}", a // b, ty)
                f.chk(f"{va} % {vb}", a % b, ty)
    return f


def gen_nested():
    f = Fixture("num_070_nested",
                "nested expressions — every emitted op wraps at "
                "width, so intermediates are modeled with per-step "
                "wrap().")
    for ty in TYPES:
        vs = boundaries(ty)
        for a, b, c in RNG().sample(
                [(x, y, z) for x in vs for y in vs for z in vs], 16):
            va, vb, vc = f.decl(ty, a), f.decl(ty, b), f.decl(ty, c)
            f.chk(f"{va} * {vb} + {vc}", wrap(a * b, ty) + c, ty)
            f.chk(f"{va} - ({vb} * {vc})", a - wrap(b * c, ty), ty)
            f.chk(f"({va} + {vb}) * {vc}", wrap(a + b, ty) * c, ty)
            f.chk(f"{va} + {vb} - {vc}", wrap(a + b, ty) - c, ty)
    return f


def gen_foldrt():
    """Fold-vs-runtime agreement: a pure-literal tree folds at the
    declared type (N29); the same shape with one runtime operand
    must produce the identical value. The fold must fit the type or
    the checker rejects — these are the in-range agreement cases."""
    f = Fixture("num_080_foldrt",
                "pure-literal folds at the declared type vs the same "
                "expression computed at runtime — must agree.")
    # (ty, folded literal tree, runtime template with {n}, operand)
    cases = [
        ("i64", "2147483647 + 1", "{n} + 1", 2147483647),
        ("i64", "9223372036854775807 - 9223372036854775806",
         "{n} - 9223372036854775806", 9223372036854775807),
        ("i64", "1 << 40", "{n} << 40", 1),
        ("i64", "-9223372036854775808 + 1", "{n} + 1",
         -9223372036854775808),
        ("u64", "18446744073709551615 - 18446744073709551614",
         "{n} - 18446744073709551614", 18446744073709551615),
        ("u64", "3 << 62", "{n} << 62", 3),
        ("u64", "18446744073709551615 >> 1",
         "{n} >> 1", 18446744073709551615),
        ("u64", "18446744073709551615 - 18446744073709551615 + 5",
         "{n} - {n} + 5", 18446744073709551615),
        ("i32", "1073741823 * 2", "{n} * 2", 1073741823),
        ("i8", "60 + 60", "{n} + 60", 60),
        ("u8", "255 - 254", "{n} - 254", 255),
        ("i16", "16000 * 2", "{n} * 2", 16000),
    ]
    i = 0
    for ty, folded, template, operand in cases:
        i += 1
        f.body.append(f"    let f{i}: {ty} = {folded};")
        n = f.decl(ty, operand)
        f.body.append(f"    let r{i}: {ty} = {template.format(n=n)};")
        f.k += 1
        f.body.append(f"    if f{i} != r{i} {{ return {f.k}; }}")
    return f


def gen_stdout():
    f = Fixture("num_090_stdout",
                "println oracles — full-width values can't fit an "
                "8-bit exit code, so stdout is compared byte-exact "
                "against num_090_stdout.stdout.")
    f.head.insert(1, "// @stdout num_090_stdout.stdout")
    f.head.append("import std.io;")
    lines = []

    def pr(expr, ty, expect):
        lines.append(str(wrap(expect, ty)))
        if signed(ty):
            f.body.append(f"    io.println_i64(i64({expr}));")
        else:
            f.body.append(f"    io.println_u64(u64({expr}));")

    pr("u64(18446744073709551615)", "u64", 2**64 - 1)
    pr("u64(18446744073709551615) + u64(1)", "u64", 0)          # wrap
    pr("u64(0) - u64(1)", "u64", 2**64 - 1)                     # underflow
    pr("i64(-9223372036854775808)", "i64", -2**63)
    pr("i64(9223372036854775807)", "i64", 2**63 - 1)
    pr("i64(9223372036854775807) + i64(1)", "i64", -2**63)      # wrap
    a = f.decl("i8", "-100")
    pr(a, "i8", -100)
    b = f.decl("u8", "255")
    pr(b, "u8", 255)
    pr(f"u64({b}) + u64(1)", "u64", 256)
    c = f.decl("i16", "-30000")
    pr(f"i64({c}) * i64(2)", "i64", -60000)                     # sext then mul
    d = f.decl("u32", "4294967295")
    pr(f"u64({d}) * u64(2)", "u64", 2 * (2**32 - 1))            # zext then mul
    f._stdout = "\n".join(lines) + "\n"
    return f


ERRORS = [
    ("num_100_err_lit_i32",
     "let x = 3000000000;", "does not fit i32"),
    ("num_101_err_lit_i8",
     "let x: i8 = 200;", "does not fit i8"),
    ("num_102_err_lit_u8",
     "let x: u8 = 300;", "does not fit u8"),
    ("num_103_err_lit_i16",
     "let x: i16 = 40000;", "does not fit i16"),
    ("num_104_err_lit_u64",
     "let x: u64 = 18446744073709551616;", "integer literal too large"),
    ("num_105_err_neglit_i32",
     "let x = 0 - 3000000000;", "does not fit i32"),
    ("num_106_err_fold_i8",
     "let x: i8 = 127 + 1;", "folds to 128, which does not fit i8"),
    ("num_107_err_fold_i32",
     "let x = 2147483647 + 1;", "folds to 2147483648, which does not fit i32"),
    ("num_108_err_fold_u64",
     "let x: u64 = 0 - 1;", "folds to -1, which does not fit u64"),
    ("num_109_err_shift_i8",
     "let a: i8 = 1; let b = a << 8;", "out of range for i8"),
    ("num_110_err_shift_i32",
     "let a: i32 = 1; let b = a << 33;", "out of range for i32"),
    ("num_111_err_lit_u16",
     "let x: u16 = 70000;", "does not fit u16"),
    ("num_112_err_fold_i16",
     "let x: i16 = 32767 + 1;", "folds to 32768, which does not fit i16"),
    ("num_113_err_fold_u8",
     "let x: u8 = 255 + 1;", "folds to 256, which does not fit u8"),
]


def gen_errors():
    for name, stmt, want in ERRORS:
        src = (
            "// @compile-error " + want + "\n"
            "// GENERATED by scripts/gen_numtests.py — do not edit.\n"
            "// Regenerate: python3 scripts/gen_numtests.py\n"
            "// expected rejection: " + want + "\n\n"
            "fn main() -> i32 {\n    " + stmt + "\n    return 42;\n}\n")
        (OUT / f"{name}.lang").write_text(src)


def main():
    gens = [
        gen_arith(SIGNED, "num_010_arith_signed",
                  "+ - * unary- on i8/i16/i32/i64"),
        gen_arith(UNSIGNED, "num_011_arith_unsigned",
                  "+ - * unary- on u8/u16/u32/u64"),
        gen_bitwise(), gen_shifts(), gen_cmp(), gen_casts(),
        gen_divmod(), gen_nested(), gen_foldrt(), gen_stdout(),
    ]
    total = 0
    for f in gens:
        n = f.write()
        total += n
        print(f"{f.name}: {n} checks")
        so = getattr(f, "_stdout", None)
        if so is not None:
            (OUT / f"{f.name}.stdout").write_bytes(so.encode())
            print(f"{f.name}.stdout: {len(so)} bytes")
    gen_errors()
    print(f"total: {total} checks + {len(ERRORS)} rejection fixtures "
          f"(seed {SEED})")


if __name__ == "__main__":
    main()
