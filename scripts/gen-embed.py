#!/usr/bin/env python3
r"""Regenerate selfhost/embed.lang — the self-hosted mirror of
compiler/build.rs (N61/N80).

Stage 0 embeds `stdlib/*.lang` and `compiler/runtime/*.{c,h}` with
include_bytes! and materializes them to $OUR_HOME/lib/<ver>/<group>/.
Stage 1 has no include_bytes, so this script emits the same table as
.lang string literals (escapes: \n \t \" \\ and \xNN for everything
else outside printable ASCII — decoded bytes are identical).

The output is checked in and verified fresh in CI (regenerate +
diff), so `ourc selfhost/our.lang` needs no generation step and the
s1->s2 self-compile embeds identical resources."""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "selfhost" / "embed.lang"
GROUPS = [("stdlib", REPO / "stdlib", (".lang",)),
          ("runtime", REPO / "compiler" / "runtime", (".c", ".h"))]

ESC = {34: '\\"', 92: "\\\\", 10: "\\n", 9: "\\t", 13: "\\r", 0: "\\0"}


def esc(data: bytes) -> str:
    out = []
    for b in data:
        if b in ESC:
            out.append(ESC[b])
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append("\\x%02X" % b)
    return "".join(out)


def main() -> int:
    files = []
    for group, d, exts in GROUPS:
        for p in sorted(d.iterdir()):
            if p.suffix in exts:
                files.append(("%s/%s" % (group, p.name), p.read_bytes()))

    lines = [
        "/// GENERATED by scripts/gen-embed.py — do not edit.",
        "/// N80: the self-hosted mirror of compiler/build.rs's",
        "/// include_bytes table — every stdlib/runtime resource as a",
        "/// string literal, materialized to $OUR_HOME/lib/0.1.0/",
        "/// <group>/ by res.lang when OUR_STDLIB/OUR_RUNTIME are",
        "/// unset. Regenerate after touching stdlib/ or",
        "/// compiler/runtime/:  python3 scripts/gen-embed.py",
        "",
        "pub fn res_count() -> i32 { return %d; }" % len(files),
        "",
        "pub fn res_name(i: i32) -> str {",
    ]
    for i, (name, _) in enumerate(files):
        lines.append('    if i == %d { return "%s"; }' % (i, name))
    lines += ['    return "";', "}", "", "pub fn res_text(i: i32) -> str {"]
    for i, (_, data) in enumerate(files):
        lines.append('    if i == %d { return "%s"; }' % (i, esc(data)))
    lines += ['    return "";', "}", ""]

    OUT.write_bytes("\n".join(lines).encode())  # LF on every host
    print("wrote %s (%d files, %d bytes)" % (OUT, len(files), OUT.stat().st_size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
